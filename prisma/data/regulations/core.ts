type CheckInput = Omit<RegulatoryCheckSeed, "isPublished" | "publishedAt" | "sortOrder" | "evidenceThreshold"> & {
  evidenceThreshold?: string;
};

function check(input: CheckInput, sortOrder = 0): RegulatoryCheckSeed {
  return {
    ...input,
    evidenceThreshold:
      input.evidenceThreshold ??
      "Норма, применимая к периоду, и первичный документ или официальная реестровая запись; отрицательный поиск сам по себе недостаточен.",
    isPublished: true,
    publishedAt: PUBLISHED_AT,
    sortOrder,
  };
}

type ProvisionInput = Omit<
  RegulationProvisionSeed,
  "isPublished" | "publishedAt" | "sortOrder" | "checks"
> & { checks: CheckInput[] };

function provision(input: ProvisionInput, sortOrder = 0): RegulationProvisionSeed {
  return {
    ...input,
    checks: input.checks.map((item, index) => check(item, index)),
    isPublished: true,
    publishedAt: PUBLISHED_AT,
    sortOrder,
  };
}

type RegulationInput = Omit<
  RegulationSeed,
  "jurisdiction" | "isPublished" | "publishedAt" | "seoTitle" | "seoDescription" | "sources" | "editions"
> & {
  provisions: RegulationProvisionSeed[];
  historicalUseAllowed?: boolean;
  verificationNote?: string;
  additionalSources?: RegulationSeed["sources"];
};

